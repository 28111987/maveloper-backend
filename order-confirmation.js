/**
 * Reduce the provenance record to what the eleven-field email can actually show:
 * the engine label, one scope chip, one 23px statement, one caption, and a tone.
 *
 * ★★ THE LLM ROUTE IS BANNED. The owner's standing rule is now: every order is
 *    COMPILER or it FAILS. So the second state this email has to render is a
 *    COMPILE FAILURE, not an LLM substitution — a design the compiler refused
 *    produces no artifact at all, and the email says exactly that.
 *
 *    The llm branch below is NOT dead code and is NOT an endorsement of the
 *    route. It exists because a record carrying engine:"llm" can still arrive
 *    from an order compiled before the ban, and an email that silently rendered
 *    such a record as a compiler ship would be the precise lie this whole file
 *    was written to prevent. It renders red, like any other non-compiler ship.
 *
 * Returns { engineLabel, chip, headline, cap, tone, state, isCompiler, fellBack }
 * where tone ∈ "lime" | "red" and drives EVERY accent in the document.
 */
export function buildLeadSummary(facts, { placeholderCount = 0 } = {}) {
  const isCompiler = facts.engine === "compiler";
  const fellBack = !!(facts.fallback && facts.fallback.occurred);
  // The compiler ran and did NOT ship: a refusal guard fired, or the record says
  // shipped:false. That is the failure state, and it is the only alternative to
  // a compiler ship now that the LLM route is closed.
  const guard = (facts.fallback && facts.fallback.guard) || facts.refusalGuard || null;
  const reason = (facts.fallback && facts.fallback.reason) || facts.refusalReason || null;
  const refused = !!guard || !!reason || !!facts.notAttemptedBecause;
  // "shipped" is the record's own word. A record that explicitly says the
  // compiler did NOT ship outranks the absence of a refusal guard.
  const saysNotShipped = facts.compilerShipped === false;

  if (isCompiler && !fellBack && !refused && !saysNotShipped) {
    const unproven = facts.proven === false || (facts.exitCode && facts.exitCode.value === 1);
    return {
      state: "shipped",
      tone: "lime",
      isCompiler: true,
      fellBack: false,
      engineLabel: facts.diamondTag
        ? `Deterministic compiler (${facts.diamondTag})`
        : "Deterministic compiler",
      chip: facts.diamondTag ? `COMPILER &middot; ${esc(facts.diamondTag)}` : "DETERMINISTIC COMPILER",
      headline: "Built by the compiler, straight from your Figma.",
      // ★ certify exit 1 means it shipped WITH known divergences (OUTPUT POLICY
      //   §8). The detail table that used to itemise them is gone, so the one
      //   caption has to carry the caveat or the lead never hears it.
      cap: unproven
        ? "The geometry was measured against your design rather than described to a model. It did not come out pixel-perfect &mdash; every difference is listed in certificate.txt inside your folder."
        : "The geometry was measured against your design rather than described to a model. Every checked property matched.",
    };
  }

  // ★★ THE FAILURE STATE. Red, and it names the guard and the verbatim reason,
  //    because "it failed" without a reason is not something a lead can act on.
  const bits = [];
  if (guard) bits.push(`the check that stopped it was <strong>${esc(guard)}</strong>`);
  if (reason) bits.push(`the reason it gave was &ldquo;${esc(reason)}&rdquo;`);

  if (fellBack || !isCompiler) {
    // A record that names an LLM substitution, from before the ban.
    return {
      state: "llm",
      tone: "red",
      isCompiler: false,
      fellBack,
      engineLabel: guard ? `LLM route &mdash; NOT the compiler (${esc(guard)})` : "LLM route &mdash; NOT the compiler",
      chip: "NOT COMPILER OUTPUT",
      headline: "This did not come from the deterministic compiler.",
      cap:
        (bits.length ? `The compiler declined this design: ${bits.join(", and ")}. ` : "The compiler did not produce this file. ") +
        "There is no pixel-level proof for it. Check it against your Figma design before you send it.",
    };
  }

  // engine:"compiler" with a refusal recorded — the compiler ran and gave up.
  return {
    state: "failed",
    tone: "red",
    isCompiler: true,
    fellBack: false,
    engineLabel: guard ? `Deterministic compiler &mdash; refused (${esc(guard)})` : "Deterministic compiler &mdash; refused",
    chip: "COMPILE FAILED",
    headline: "The compiler could not build this order.",
    cap:
      (bits.length
        ? `It stopped before it produced a file: ${bits.join(", and ")}. `
        : "It stopped before it produced a file. ") +
      "Nothing was built, so there is no HTML and no delivery folder for this order yet. We are on it &mdash; you do not need to re-submit.",
  };
}


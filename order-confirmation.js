/**
 * Plain-text alternative. Not decoration: a text/plain part is what keeps this
 * out of a spam classifier's "HTML-only" bucket, and it is the copy a screen
 * reader and a text-mode client actually get. Same eleven fields, same order.
 */
export function renderConfirmationText(view) {
  const { orderId, summary, fields, placeholder, fromAddress } = view;
  const strip = (s) =>
    String(s)
      .replace(/<[^>]*>/g, "")
      .replace(/&mdash;/g, "—")
      .replace(/&rarr;/g, "→")
      .replace(/&middot;/g, "·")
      .replace(/&ldquo;|&rdquo;/g, '"')
      .replace(/&hellip;/g, "…")
      .replace(/&times;/g, "×")
      .replace(/&nbsp;/g, " ")
      .replace(/&#39;/g, "'")
      .replace(/&quot;/g, '"')
      .replace(/&amp;/g, "&");

  const failed = summary.tone === "red";
  const L = [];
  L.push(`MAVELOPER — ${failed ? "ORDER HELD" : "ORDER CONFIRMED"}`);
  L.push("=".repeat(failed ? 25 : 30));
  L.push(failed ? "This order did not build." : "Your email is built.");
  L.push("");
  if (placeholder.count > 0) {
    L.push(
      `★ ${placeholder.count} placeholder link${placeholder.count === 1 ? "" : "s"} still point${
        placeholder.count === 1 ? "s" : ""
      } to "#" — this email is not sendable until ${placeholder.count === 1 ? "it is" : "they are"} replaced.`,
    );
    L.push("");
  }
  L.push("THE ORDER");
  L.push("---------");
  L.push(`Order ID: ${strip(orderId)}`);
  for (const p of fields.order) L.push(`${p.label}: ${strip(p.value)}`);
  L.push("");
  L.push("THE BUILD");
  L.push("---------");
  L.push(strip(summary.headline));
  L.push(strip(summary.cap));
  L.push("");
  for (const p of fields.build) L.push(`${p.label}: ${strip(p.value)}`);
  if (fields.links.length) {
    L.push("");
    L.push("YOUR FILES");
    L.push("----------");
    const w = Math.max(...fields.links.map((l) => l.label.length));
    for (const l of fields.links) L.push(`${l.label.padEnd(w)} : ${l.href}`);
  }
  L.push("");
  L.push(`Maveloper · ${BRAND_ATTRIBUTION}`);
  L.push(`This is an automated order confirmation. Please do not reply — replies to ${fromAddress} are not monitored.`);
  return L.join("\n") + "\n";
}


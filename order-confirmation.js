// Every construct below is chosen for the Word rendering engine (Outlook
// 2007-2019): nested tables with role="presentation", explicit width/bgcolor
// ATTRIBUTES alongside inline styles, no flexbox, no grid, no border-radius, no
// external stylesheet, no <style> dependency for anything load-bearing. The
// single <style> block carries ONLY progressive enhancement — the dark-client
// handling and the 600px stack — and the email is correct with it stripped.

const PAD = "50px 46px"; // emSec_, as the reference specifies

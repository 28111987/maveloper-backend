    fallback,
    // compiler.notAttemptedBecause distinguishes "the compiler refused" from
    // "the compiler was never asked" — two very different things to tell a lead.
    notAttemptedBecause: at(p, "compiler.notAttemptedBecause") || null,
    // ★ THE REFUSAL, READ INDEPENDENTLY OF THE FALLBACK BLOCK. Now that the LLM
    //   route is banned, a compiler that refuses does NOT hand off — it fails,
    //   and the record carries fallback.occurred:false with the guard sitting
    //   only at compiler.refusalGuard. Reading the guard exclusively through the
    //   fallback block would render that order as a clean ship.
    refusalGuard: (typeof at(p, "compiler.refusalGuard") === "string" ? at(p, "compiler.refusalGuard") : null) || null,
    refusalReason: (typeof at(p, "compiler.refusalReason") === "string" ? at(p, "compiler.refusalReason") : null) || null,
    compilerShipped: typeof at(p, "compiler.shipped") === "boolean" ? at(p, "compiler.shipped") : null,

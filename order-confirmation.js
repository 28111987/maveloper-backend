/** #RRGGBB → {r,g,b}. */
function hex2rgb(h) {
  const m = /^#?([0-9a-f]{6})$/i.exec(String(h).trim());
  if (!m) return { r: 0, g: 0, b: 0 };
  const n = parseInt(m[1], 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
}

/** Blend two hexes. t=0 → a, t=1 → b. */
function mixHex(a, b, t) {
  const A = hex2rgb(a);
  const B = hex2rgb(b);
  const c = (x, y) => Math.round(x + (y - x) * t).toString(16).padStart(2, "0");
  return `#${c(A.r, B.r)}${c(A.g, B.g)}${c(A.b, B.b)}`;
}

/** A hex at an alpha, for the band glows. */
function rgba(h, a) {
  const { r, g, b } = hex2rgb(h);
  return `rgba(${r},${g},${b},${a})`;
}

/**
 * ★ qbGradText_ — A PER-CHARACTER COLOUR RAMP.
 *
 * The reference calls this "the only text gradient that survives Gmail", and it
 * survives because there is no gradient: every character is its own <span> with
 * its own solid colour, so a client that supports nothing but `color` still
 * draws the ramp. background-clip:text, which is how this effect is normally
 * done on the web, is stripped by Gmail and by Outlook and would leave the text
 * invisible or flat.
 *
 * ★ SPENT ONCE, ON THE ONE VALUE WORTH IT: the ORDER ID. It is the single string
 *   the lead will quote back to us, search their inbox for, and paste into a
 *   message — so it is the email's anchor and it gets the ramp. Never prose:
 *   one <span> per character over a paragraph is both unreadable markup and a
 *   real cost in bytes against Gmail's clip threshold.
 */
export function qbGradText(str, from, to, style = "") {
  const chars = Array.from(String(str));
  if (!chars.length) return "";
  const last = Math.max(chars.length - 1, 1);
  return chars
    .map((ch, i) => {
      const c = mixHex(from, to, i / last);
      const body = ch === " " ? "&nbsp;" : esc(ch);
      return `<span style="color:${c};${style}">${body}</span>`;
    })
    .join("");
}

